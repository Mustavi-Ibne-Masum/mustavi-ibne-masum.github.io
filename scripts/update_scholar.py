"""Fetch publication and citation counts from Google Scholar into _data/scholar.yml.

Run locally:  python scripts/update_scholar.py
Also runs weekly from .github/workflows/scholar.yml.
If Scholar blocks the request, the existing file is left untouched.
"""
import datetime, pathlib, re, sys, urllib.request

USER = "8RSb1v0AAAAJ"
URL = f"https://scholar.google.com/citations?user={USER}&hl=en&pagesize=100"
OUT = pathlib.Path(__file__).resolve().parent.parent / "_data" / "scholar.yml"

req = urllib.request.Request(URL, headers={
    "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
                  "(KHTML, like Gecko) Chrome/124.0 Safari/537.36",
    "Accept-Language": "en-US,en;q=0.9",
})
try:
    page = urllib.request.urlopen(req, timeout=30).read().decode("utf-8", "ignore")
except Exception as e:
    sys.exit(f"Could not reach Google Scholar ({e}); keeping existing data.")

stats = re.findall(r'class="gsc_rsb_std">(\d+)<', page)
pubs = len(re.findall(r'class="gsc_a_tr"', page))
if len(stats) < 6 or pubs == 0:
    sys.exit("Scholar page did not look right (blocked or CAPTCHA?); keeping existing data.")

citations, h_index, i10 = int(stats[0]), int(stats[2]), int(stats[4])
OUT.write_text(
    "# Auto-generated by scripts/update_scholar.py. Do not edit by hand.\n"
    f"profile: \"https://scholar.google.com/citations?user={USER}\"\n"
    f"publications: {pubs}\n"
    f"citations: {citations}\n"
    f"h_index: {h_index}\n"
    f"i10_index: {i10}\n"
    f"updated: {datetime.date.today().isoformat()}\n",
    encoding="utf-8",
)
print(f"publications={pubs} citations={citations} h={h_index} i10={i10}")
